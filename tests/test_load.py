"""Checks the population and cross-row rules that SQL foreign keys cannot enforce."""
from datetime import datetime, timedelta, timezone
import importlib.util
import json
from pathlib import Path
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('m2_load', ROOT / 'ingest/load.py')
loader = importlib.util.module_from_spec(spec)
spec.loader.exec_module(loader)


class CollectionRules(unittest.TestCase):
    def setUp(self):
        self.anchor = datetime(2026, 11, 5, 12, tzinfo=timezone.utc)
        self.game = json.loads((ROOT / 'data/sample/match_sample.json').read_text(encoding='utf-8'))
        self.game['info']['gameStartTimestamp'] = int((self.anchor-timedelta(hours=1)).timestamp()*1000)
        self.game['info']['endOfGameResult'] = 'GameComplete'
        self.selected = {self.game['info']['participants'][0]['puuid']}
        self.champions = {p['championId'] for p in self.game['info']['participants']}

    def reason(self):
        return loader.validate_match(self.game, self.selected, self.anchor, self.champions)

    def test_only_one_selected_player_is_enough(self):
        self.assertIsNone(self.reason())

    def test_window_is_half_open(self):
        self.game['info']['gameStartTimestamp'] = int((self.anchor-timedelta(hours=24)).timestamp()*1000)
        self.assertIsNone(self.reason())
        self.game['info']['gameStartTimestamp'] = int(self.anchor.timestamp()*1000)
        self.assertEqual(self.reason(), 'outside_window')

    def test_scheduled_window_recovers_matches_older_than_one_day(self):
        self.game['info']['gameStartTimestamp'] = int((self.anchor-timedelta(hours=36)).timestamp()*1000)
        self.assertEqual(self.reason(), 'outside_window')
        self.assertIsNone(loader.validate_match(self.game, self.selected, self.anchor, self.champions, window_hours=48))
        self.game['info']['gameStartTimestamp'] = int((self.anchor-timedelta(hours=48)).timestamp()*1000)
        self.assertIsNone(loader.validate_match(self.game, self.selected, self.anchor, self.champions, window_hours=48))

    def test_requires_selected_player(self):
        self.selected = {'not_in_game'}
        self.assertEqual(self.reason(), 'no_selected_player')

    def test_duplicate_participant_is_rejected(self):
        self.game['info']['participants'][1]['puuid'] = self.game['info']['participants'][0]['puuid']
        self.assertEqual(self.reason(), 'invalid_participant_count_or_identity')

    def test_inconsistent_win_is_rejected(self):
        person = self.game['info']['participants'][0]
        person['win'] = not person['win']
        self.assertEqual(self.reason(), 'inconsistent_participant_outcomes')

    def test_short_game_is_not_silently_filtered(self):
        self.game['info']['gameDuration'] = 100
        self.assertIsNone(self.reason())

    def test_transform_normalizes_role_and_converts_milliseconds(self):
        self.game['info']['participants'][0]['teamPosition'] = ''
        match, people = loader.match_rows(self.game)
        self.assertEqual(match['game_start'], self.anchor-timedelta(hours=1))
        self.assertIsNone(people[0]['team_position'])
        self.assertNotIn('patch', match)  # Generated by PostgreSQL.

    def test_trim_drops_player_display_identifiers(self):
        self.game['info']['participants'][0]['riotIdGameName'] = 'do not retain'
        result = loader.trim_match(self.game)
        self.assertNotIn('riotIdGameName', result['info']['participants'][0])

    def test_history_pagination_preserves_both_time_bounds(self):
        client = loader.RiotClient()
        requests = []
        def fake_get(url, params=None, label=''):
            requests.append(dict(params))
            return ['NA1_' + str(i) for i in range(100)] if len(requests) == 1 else []
        client._get = fake_get
        result = client.match_ids_since('synthetic-player', 1000, 2000)
        self.assertEqual(len(result), 100)
        self.assertEqual([p['start'] for p in requests], [0, 100])
        self.assertTrue(all(p['startTime'] == 1000 and p['endTime'] == 2000 and p['queue'] == 420
                            for p in requests))


if __name__ == '__main__':
    unittest.main()
